// Ось импорта по работодателю — рядом с OCCUPATIONS (src/lib/occupations.ts),
// не внутри src/lib/importers/jobtech.ts: список подрядчиков и регион-
// приоритет это конфигурация, а не логика импортёра.
//
// Зачем вообще эта ось: проверено на реальном API 16.08.2026 — ось по
// occupation-термину слабее оси по работодателю. N Kraft Bemanning AB
// (кадровое агентство, возит бригады на Luleå/Boden) отдаёт 1547 вакансий
// по всей Швеции, но только четверть их заголовков попадает под термины
// поиска ("Helpers", "Dumperchaufförer" и т.п. — синонимов не напасёшься).
// Проще искать по имени известного подрядчика напрямую.
//
// Список смешанный по типу — это осознанно, не недосмотр:
//   - N Kraft Bemanning, ExpanderaMera, MW Sverige/MW Field Services —
//     кадровые агентства, сами не строят ничего, только поставляют людей
//     на чужие площадки под заказ.
//   - NCC — генподрядчик (сам строит), не агентство. Добавлен, потому что
//     при проверке 16.08.2026 его непойманные текущими терминами заголовки
//     оказались НАСТОЯЩИМИ рабочими вакансиями («Erfarna maskinister till
//     pålkran» x10, «Yrkesarbetare till Fräsverksamhet Asfalt Nord» x8) —
//     NCC просто публикует их сам, под свою терминологию, а не через
//     агентство. Критерий отбора в список — не "агентство или нет", а
//     "публикует ли реальные рабочие вакансии под своим именем",
//     проверено чтением заголовков, не предположением по типу компании.
//
// Stegra и Boliden — оба крупные, оба сидят в целевом регионе географически
// сильнее многих, и по этому одному признаку выглядели бы кандидатами не
// хуже NCC. Проверены той же процедурой (чтение реальных заголовков
// 16.08.2026) и НЕ добавлены: то, что они публикуют от своего имени —
// в основном офисные и управленческие роли (Treasury Analyst, Head of
// Internal Audit, Sektionschef, Underhållschef). Похоже, что их синие
// воротнички нанимаются как раз через таких подрядчиков/агентства, что уже
// в списке (не проверено напрямую — это вывод по отсутствию рабочих вакансий
// от их лица, не подтверждённый факт об их процессе найма). Добавление
// Stegra/Boliden в whitelist при том же лимите на запрос вытеснило бы
// реальные рабочие вакансии NCC/N Kraft заголовками вроде "Treasury
// Analyst" — та же логика проверки, что привела к включению NCC, привела
// к исключению этих двух.
// Известный, не срочный побочный эффект (16.08.2026): исключённый через
// excluded_vacancies работодатель (по employer_name) продолжит попадать
// в выдачу employer-прохода при каждом импорте — фильтр в route.ts всё
// равно отсеет его до записи в БД (проверено: работает на объединённом
// результате обоих проходов, см. комментарий в api/import/route.ts), так
// что обещание "уберём вакансию" не нарушается. Просто лишний HTTP-запрос
// к JobTech на каждый прогон, если когда-нибудь исключат кого-то из этого
// списка. Не оптимизировать заранее — сначала нужен реальный такой случай.
