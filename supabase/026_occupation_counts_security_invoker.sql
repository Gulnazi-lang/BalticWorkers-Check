-- Закрывает предупреждение Security Advisor: "Security Definer View" на
-- public.occupation_counts (23.09.2026).
--
-- В Postgres view до явного указания security_invoker выполняется с правами
-- ВЛАДЕЛЬЦА, а не запрашивающей роли — то есть по умолчанию ведёт себя как
-- security definer, даже без явного объявления. Комментарий в 012 писал
-- "не security definer" как намерение, но не как факт: сама конструкция
-- `create view` этого не гарантирует без опции ниже.
--
-- Практической утечки не было: view сам фильтрует `published = true`, то
-- есть RLS-политика vacancies и так ничего лишнего не пропустила бы. Но
-- структурно RLS таблицы должен применяться через view тоже — на случай,
-- если политика когда-то станет строже (скрыть колонку, ограничить по
-- региону и т.п.), а view незаметно продолжит её обходить.
--
-- Доступно с PostgreSQL 15; Supabase создаёт новые проекты на более новой
-- версии, так что миграция должна пройти без ошибок.

alter view public.occupation_counts set (security_invoker = true);
